function baseFixedName(g) {
  return String(g?.nombreBase || g?.nombre || '').replace(/\s*\(deuda arrastrada.*\)$/i, '').trim();
}

function regularFixedExpensesSource(sourceMonth) {
  return (sourceMonth?.gastosFijos || []).filter((g) => !g.arrastradoDe).map((g) => ({
    id: uid(),
    nombre: String(g.nombre || ''),
    monto: parseAmountInput(g.monto ?? 0),
    pagado: false,
    arrastradoDe: '',
    nombreBase: '',
  }));
}

function cloneFixedExpenses(sourceMonth) {
  return sortFixedExpensesList(regularFixedExpensesSource(sourceMonth));
}

function buildCarryoverFixedExpenses(sourceMonthKey, sourceMonth) {
  return sortFixedExpensesList((sourceMonth?.gastosFijos || [])
    .filter((g) => !g.pagado && parseAmountInput(g.monto || 0) > 0 && String(g.nombre || '').trim())
    .map((g) => ({
      id: uid(),
      nombre: `${baseFixedName(g)} (deuda arrastrada ${sourceMonthKey})`,
      nombreBase: baseFixedName(g),
      monto: parseAmountInput(g.monto || 0),
      pagado: false,
      arrastradoDe: sourceMonthKey,
    })));
}

function buildCarryoverCommitments(sourceMonthKey, sourceMonth) {
  return (sourceMonth?.gastosFijos || [])
    .filter((g) => !g.pagado && parseAmountInput(g.monto || 0) > 0 && String(g.nombre || '').trim())
    .map((g) => ({
      id: uid(),
      tipo: 'saldo',
      nombre: `${baseFixedName(g)} · deuda arrastrada ${sourceMonthKey}`,
      saldoPendiente: parseAmountInput(g.monto || 0),
      historial: [{ id: uid(), fecha: today(), monto: parseAmountInput(g.monto || 0), texto: `Arrastre automático desde ${sourceMonthKey}` }],
      carryoverSourceMonth: sourceMonthKey,
      carryoverSourceName: baseFixedName(g),
      observaciones: `Deuda arrastrada del gasto fijo ${baseFixedName(g)} de ${sourceMonthKey}`,
    }));
}

function mergeNextMonthFixedExpenses(baseRegular, carryovers, existingMonth) {
  const existingNonCarry = (existingMonth?.gastosFijos || []).filter((g) => !g.arrastradoDe);
  const base = existingMonth?.fixedCustomized && existingNonCarry.length ? existingNonCarry.map((g) => ({ ...g, id: uid() })) : baseRegular;
  return sortFixedExpensesList([...(base || []), ...(carryovers || [])]);
}

function nextMonthKey(monthKey) {
  const [y, m] = String(monthKey).split('-').map(Number);
  const d = new Date(y, m, 1);
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}`;
}

function applyCloseMonthCarryover(monthKey) {
  const sourceMonth = state.months[monthKey] || baseMonth();
  const nextKey = nextMonthKey(monthKey);
  const existingNext = state.months[nextKey] || { movimientos: [] };
  const baseRegular = cloneFixedExpenses(sourceMonth);
  state.months[nextKey] = {
    ...existingNext,
    fixedCustomized: !!existingNext.fixedCustomized,
    autoGenerated: true,
    carryoverGenerated: false,
    gastosFijos: mergeNextMonthFixedExpenses(baseRegular, [], existingNext),
    movimientos: Array.isArray(existingNext.movimientos) ? existingNext.movimientos : [],
  };

  const newCarryoverCommitments = buildCarryoverCommitments(monthKey, sourceMonth);
  const existingCommitments = (state.compromisos || []).filter((c) => c.carryoverSourceMonth !== monthKey);
  state.compromisos = [...newCarryoverCommitments, ...existingCommitments];
  sourceMonth.closedCarryoverToCommitments = true;
  return { nextKey, carryoversCount: newCarryoverCommitments.length };
}

function sortFixedExpensesList(items) {
  return [...(items || [])].sort((a, b) => {
    const diff = Number(b?.monto || 0) - Number(a?.monto || 0);
    if (diff !== 0) return diff;
    return String(a?.nombre || '').localeCompare(String(b?.nombre || ''), 'es', { sensitivity: 'base' });
  });
}

function hasMeaningfulFixedExpenses(month) {
  const fixed = month?.gastosFijos || [];
  return fixed.some((g) => String(g?.nombre || '').trim() || Number(g?.monto || 0) !== 0);
}

function isPlaceholderMonth(month) {
  if (!month) return true;
  const movimientos = Array.isArray(month.movimientos) ? month.movimientos : [];
  const fixed = Array.isArray(month.gastosFijos) ? month.gastosFijos : [];
  return movimientos.length === 0 && fixed.length > 0 && fixed.every((g) => Number(g?.monto || 0) === 0 && !g?.pagado);
}

function isUntouchedMonth(month) {
  if (!month) return true;
  const movimientos = Array.isArray(month.movimientos) ? month.movimientos : [];
  const fixed = Array.isArray(month.gastosFijos) ? month.gastosFijos : [];
  return movimientos.length === 0 && fixed.every((g) => !g?.pagado) && !month.fixedCustomized;
}

function fixedNamesSignature(month) {
  return (month?.gastosFijos || [])
    .map((g) => String(g?.nombre || '').trim().toLowerCase())
    .filter(Boolean)
    .join('|');
}

function sameFixedExpenses(a, b) {
  const aa = (a?.gastosFijos || []).map((g) => `${String(g?.nombre || '').trim().toLowerCase()}::${parseAmountInput(g?.monto || 0)}`);
  const bb = (b?.gastosFijos || []).map((g) => `${String(g?.nombre || '').trim().toLowerCase()}::${parseAmountInput(g?.monto || 0)}`);
  return aa.join('|') === bb.join('|');
}

function isLikelyCorruptedAutoMonth(month, referenceMonth) {
  if (!month || !referenceMonth) return false;
  const movimientos = Array.isArray(month.movimientos) ? month.movimientos : [];
  const fixed = Array.isArray(month.gastosFijos) ? month.gastosFijos : [];
  const refFixed = Array.isArray(referenceMonth.gastosFijos) ? referenceMonth.gastosFijos : [];
  if (movimientos.length > 0) return false;
  if (!fixed.length || !refFixed.length) return false;
  const allPending = fixed.every((g) => !g?.pagado);
  const namesDiffer = fixedNamesSignature(month) !== fixedNamesSignature(referenceMonth);
  const suspiciousFixed495 = fixed.length > 0 && fixed.every((g) => Number(g?.monto || 0) === 495000);
  const suspiciousTotal495 = fixed.reduce((acc, g) => acc + Number(g?.monto || 0), 0) === 495000;
  return allPending && (namesDiffer || suspiciousFixed495 || suspiciousTotal495 || isPlaceholderMonth(month));
}

function markCurrentMonthFixedCustomized() {
  const month = currentMonthData();
  month.fixedCustomized = true;
  month.autoGenerated = false;
}

function previousMonthKey(monthKey) {
  const [y, m] = String(monthKey).split('-').map(Number);
  const d = new Date(y, (m || 1) - 2, 1);
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}`;
}

function findReferenceMonthForNewMonth(monthKey, sourceMonthKey = state.currentMonth) {
  const directPreviousKey = previousMonthKey(monthKey);
  const directPrevious = state.months[directPreviousKey];
  if (hasMeaningfulFixedExpenses(directPrevious)) return directPrevious;

  const explicitSource = state.months[sourceMonthKey];
  if (hasMeaningfulFixedExpenses(explicitSource)) return explicitSource;

  const allMonths = Object.entries(state.months || {})
    .filter(([key]) => key < monthKey)
    .sort((a, b) => b[0].localeCompare(a[0]))
    .map(([, value]) => value);

  const withFixed = allMonths.find((m) => hasMeaningfulFixedExpenses(m));
  return withFixed || explicitSource || baseMonth();
}

function shouldResyncMonthFromPrevious(monthKey) {
  const current = state.months[monthKey];
  const prev = state.months[previousMonthKey(monthKey)];
  if (!current || current.closedAt) return false;
  if (!prev || !hasMeaningfulFixedExpenses(prev)) return false;
  if (current.fixedCustomized || current.carryoverGenerated) return false;
  if (!isUntouchedMonth(current) && !isLikelyCorruptedAutoMonth(current, prev)) return false;
  if (sameFixedExpenses(current, prev) && hasMeaningfulFixedExpenses(current)) return false;
  return isPlaceholderMonth(current) || isLikelyCorruptedAutoMonth(current, prev) || (current.autoGenerated && !sameFixedExpenses(current, prev));
}

function createMonthFromReference(reference) {
  return {
    fixedCustomized: false,
    autoGenerated: true,
    carryoverGenerated: false,
    gastosFijos: cloneFixedExpenses(reference),
    movimientos: [],
  };
}

function ensureMonth(monthKey, sourceMonthKey = state.currentMonth, { forceFromSource = false } = {}) {
  const sourceReference = state.months[sourceMonthKey];
  const reference = forceFromSource && hasMeaningfulFixedExpenses(sourceReference)
    ? sourceReference
    : findReferenceMonthForNewMonth(monthKey, sourceMonthKey);
  const existing = state.months[monthKey];

  if (!existing) {
    state.months[monthKey] = createMonthFromReference(reference);
    return;
  }

  if (!Object.prototype.hasOwnProperty.call(existing, 'fixedCustomized')) existing.fixedCustomized = false;
  if (!Object.prototype.hasOwnProperty.call(existing, 'autoGenerated')) existing.autoGenerated = false;
  if (!Object.prototype.hasOwnProperty.call(existing, 'carryoverGenerated')) existing.carryoverGenerated = false;
  if (shouldResyncMonthFromPrevious(monthKey)) {
    state.months[monthKey] = {
      ...existing,
      fixedCustomized: false,
      autoGenerated: true,
      carryoverGenerated: false,
      gastosFijos: cloneFixedExpenses(state.months[previousMonthKey(monthKey)]),
      movimientos: Array.isArray(existing.movimientos) ? existing.movimientos : [],
    };
    return;
  }

  const existingHasMeaningfulFixed = hasMeaningfulFixedExpenses(existing);
  const existingLooksPlaceholder = isPlaceholderMonth(existing);
  const existingLooksCorrupted = isLikelyCorruptedAutoMonth(existing, reference);

  if ((!existingHasMeaningfulFixed || existingLooksPlaceholder || existingLooksCorrupted) && hasMeaningfulFixedExpenses(reference)) {
    state.months[monthKey] = {
      ...existing,
      fixedCustomized: false,
      autoGenerated: true,
      carryoverGenerated: false,
      gastosFijos: cloneFixedExpenses(reference),
      movimientos: Array.isArray(existing.movimientos) ? existing.movimientos : [],
    };
  }
}

function repairCurrentMonthFromPrevious() {
  const currentKey = state.currentMonth;
  const prevKey = previousMonthKey(currentKey);
  const prevMonth = state.months[prevKey];
  if (!hasMeaningfulFixedExpenses(prevMonth)) {
    alert('No encontré un mes anterior válido para usar como referencia.');
    return;
  }
  const existing = state.months[currentKey] || { movimientos: [] };
  state.months[currentKey] = {
    ...existing,
    fixedCustomized: false,
    autoGenerated: true,
    carryoverGenerated: false,
    gastosFijos: cloneFixedExpenses(prevMonth),
    movimientos: Array.isArray(existing.movimientos) ? existing.movimientos : [],
  };
  render();
  saveState();
  alert(`Mes reparado tomando como referencia ${prevKey}.`);
}

function repairMonthChainFromPrevious() {
  const keys = Object.keys(state.months || {}).sort();
  keys.forEach((key) => {
    const month = state.months[key];
    if (!month) return;
    if (!Object.prototype.hasOwnProperty.call(month, 'fixedCustomized')) month.fixedCustomized = false;
    if (!Object.prototype.hasOwnProperty.call(month, 'autoGenerated')) month.autoGenerated = false;
    if (shouldResyncMonthFromPrevious(key)) {
      const prev = state.months[previousMonthKey(key)];
      state.months[key] = {
        ...month,
        fixedCustomized: false,
        autoGenerated: true,
        carryoverGenerated: false,
        gastosFijos: cloneFixedExpenses(prev),
        movimientos: Array.isArray(month.movimientos) ? month.movimientos : [],
      };
    }
  });
}

