function submitExpressForm(ev) {
  ev.preventDefault();
  const fd = new FormData(ev.target);
  const mode = fd.get('mode') || 'pedido';
  const feedback = document.getElementById('expressFeedback');
  const say = (msg, type='info') => { if (feedback) { feedback.textContent = msg; feedback.dataset.type = type; } };
  try {
    if (mode === 'pedido' || mode === 'pasajero') {
      const section = mode === 'pedido' ? 'pedidos' : 'pasajeros';
      const cliente = ensureAssistantClient(String(fd.get('cliente') || '').trim());
      const qty = Number(fd.get('cantidad') || 0);
      const detalle = String(fd.get('detalle') || '').trim();
      const cobro = inferTripLineTotal(section, { rawCobro: fd.get('total') || '', detalle, cantidad: qty });
      if (!cliente) throw new Error('Cargá el cliente.');
      if (!cobro) throw new Error('No pude calcular el total.');
      const cobradoInicial = inferTripLineCollected(fd.get('cobrado') || '', cobro);
      const finalDetalle = section === 'pedidos' && qty > 0 && !detalle ? `${qty} pedido${qty > 1 ? 's' : ''}` : detalle;
      currentTrip()[section].unshift(normalizeTripLine({
        id: uid(), cliente, detalle: finalDetalle, cobro, cobradoActual: cobradoInicial, pagos: buildInitialPayments(cobro, cobradoInicial),
      }));
      say(`${mode === 'pedido' ? 'Pedido' : 'Pasajero'} agregado para ${cliente}.`, 'success');
      logAction('viaje', `Carga exprés: ${mode} para ${cliente}`);
    } else if (mode === 'pago') {
      const cliente = normalizeAssistantClientName(String(fd.get('cliente') || '').trim());
      const amount = parseAmountInput(fd.get('total') || 0);
      if (!cliente || !amount) throw new Error('Cargá cliente y monto.');
      let applied = applyPaymentToTripClient(cliente, amount);
      if (applied < amount) applied += applyPaymentToDebtor(cliente, amount - applied);
      if (!applied) throw new Error(`No encontré pendientes para ${cliente}.`);
      say(`Registré ${money(applied)} para ${cliente}.`, 'success');
      logAction('viaje', `Carga exprés: pago de ${money(applied)} para ${cliente}`);
    } else if (mode === 'gasto') {
      const categoria = String(fd.get('categoria') || '').trim() || 'Otros';
      const detalle = String(fd.get('detalle') || '').trim();
      const monto = parseAmountInput(fd.get('total') || 0);
      if (!monto) throw new Error('Cargá el monto del gasto.');
      currentTrip().gastos.unshift({ id: uid(), categoria, detalle, monto });
      if (!(state.tripExpenseCategories || []).includes(categoria)) state.tripExpenseCategories.push(categoria);
      say(`Gasto ${categoria} agregado por ${money(monto)}.`, 'success');
      logAction('viaje', `Carga exprés: gasto ${categoria}`);
    } else if (mode === 'movimiento') {
      const tipo = String(fd.get('moveType') || 'gasto');
      const categoria = String(fd.get('categoria') || '').trim();
      const descripcion = String(fd.get('detalle') || '').trim();
      const monto = parseAmountInput(fd.get('total') || 0);
      if (!categoria || !monto) throw new Error('Cargá categoría y monto.');
      currentMonthData().movimientos.unshift({ id: uid(), fecha: today(), tipo, categoria, descripcion, monto });
      say(`Movimiento ${categoria} agregado por ${money(monto)}.`, 'success');
      logAction('plata', `Carga exprés: movimiento ${categoria}`);
    } else if (mode === 'mantenimiento') {
      const vehicleId = String(fd.get('vehicleId') || currentMaintenanceVehicleId());
      const tipo = String(fd.get('maintenanceType') || '').trim();
      const fecha = String(fd.get('fecha') || today());
      const km = parseKmInput(fd.get('km') || 0);
      const detalle = String(fd.get('detalle') || '').trim();
      if (!tipo || !km) throw new Error('Cargá tipo y kilometraje.');
      state.maintenanceItems.unshift({ id: uid(), vehicleId, tipo, fecha, km, detalle });
      state.maintenanceItems.sort((a,b) => String(b.fecha).localeCompare(String(a.fecha)) || Number(b.km||0)-Number(a.km||0));
      say(`Mantenimiento ${tipo} cargado.`, 'success');
      logAction('mantenimiento', `Carga exprés: ${tipo}`);
    }
    ev.target.reset();
    const modeEl = document.getElementById('expressMode');
    if (modeEl) modeEl.value = mode;
    updateExpressModeUI();
    render();
  } catch (err) {
    say(err.message || 'No pude procesar la carga exprés.', 'error');
  }
}


function setClientPaidStatus(clientName, paid) {
  const trip = currentTrip();
  migrateTripToUnifiedPedidos(trip);
  ['pasajeros', 'pedidos'].forEach((section) => {
    (trip[section] || []).forEach((item) => {
      if (norm(item.cliente) === norm(clientName)) {
        normalizeTripLine(item);
        item.cobradoActual = paid ? Number(item.cobro || 0) : 0;
        item.pagado = !!paid;
      }
    });
  });
  render();
}

